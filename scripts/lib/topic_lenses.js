const DEFAULT_LENS = { label: 'what the documents say', ask: 'What do the documents say?', check: 'Gather the agreement, the messages and the payment record, and put them in date order.' };

const MAX_LENSES = 4;

function lensesFor(page) {
  const text = [page.title, page.slug].filter(Boolean).join(' ').replace(/[-/]+/g, ' ');
  const found = LENSES.filter((l) => l.re.test(text));
  const cluster = { id: `cluster:${page.cluster || ''}`, ...(CLUSTER_LENS[page.cluster] || DEFAULT_LENS) };
  const picked = found.slice(0, MAX_LENSES);
  if (picked.length < 2 && !picked.some((l) => l.label === cluster.label)) picked.push(cluster);
  return picked;
}

function joinLabels(labels) {
  if (labels.length <= 1) return labels.join('');
  return `${labels.slice(0, -1).join(', ')} and ${labels[labels.length - 1]}`;
}

